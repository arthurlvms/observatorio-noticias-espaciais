PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS raw(
 id INTEGER PRIMARY KEY, payload TEXT NOT NULL, dirty INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS ix_raw_pending ON raw(dirty);
CREATE TABLE IF NOT EXISTS audit(
 run INTEGER PRIMARY KEY, stage TEXT NOT NULL, detail TEXT NOT NULL,
 finished_utc TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS dim_artigo(
 sk_artigo INTEGER PRIMARY KEY, id_fonte INTEGER NOT NULL UNIQUE,
 titulo TEXT NOT NULL, resumo TEXT NOT NULL, url TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS dim_tempo(
 sk_tempo INTEGER PRIMARY KEY, data TEXT NOT NULL UNIQUE, ano INTEGER NOT NULL,
 mes INTEGER NOT NULL, dia INTEGER NOT NULL, trimestre INTEGER NOT NULL, dia_iso INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS dim_veiculo(sk_veiculo INTEGER PRIMARY KEY, nome TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS fato_publicacao(
 sk_artigo INTEGER PRIMARY KEY REFERENCES dim_artigo,
 sk_tempo INTEGER NOT NULL REFERENCES dim_tempo, sk_veiculo INTEGER NOT NULL REFERENCES dim_veiculo,
 quantidade INTEGER NOT NULL CHECK(quantidade=1),
 mencoes_lancamento INTEGER NOT NULL CHECK(mencoes_lancamento>=0)
);
